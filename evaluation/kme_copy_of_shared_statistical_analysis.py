def cliffs_delta(x, y):
    """Cliff's delta effect size: P(X>Y) - P(X<Y)."""
    x, y = np.asarray(x), np.asarray(y)
    diff = x[:, None] - y[None, :]
    return (np.sum(diff > 0) - np.sum(diff < 0)) / (len(x) * len(y))

def run_stats(df, label="All Files"):
    groups = ["Expert 1 Ratings", "Expert 2 Ratings", "o3 Text, Text + Image"]
    samples = [df.loc[df["group"] == g, "rating"].values for g in groups]

    kw_stat, kw_p = kruskal(*samples)
    print(f"\n=== {label} ===")
    print(f"Kruskal–Wallis H={kw_stat:.3f}, p={kw_p:.3g}")

    # Pairwise Mann–Whitney with Bonferroni
    pairs = list(combinations(groups, 2))
    m = len(pairs)
    rows = []
    for a, b in pairs:
        xa = df.loc[df["group"] == a, "rating"].values
        xb = df.loc[df["group"] == b, "rating"].values
        U, p = mannwhitneyu(xa, xb, alternative="two-sided")
        p_bonf = min(p * m, 1.0)
        delta = cliffs_delta(xa, xb)
        rows.append([a, b, len(xa), len(xb), U, p, p_bonf, delta])
    out = pd.DataFrame(rows, columns=["Group A","Group B","nA","nB","U","p_raw","p_bonf","Cliffs_delta"])
    print(out.to_string(index=False))


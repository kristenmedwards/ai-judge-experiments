def get_top_set_with_ties(ratings, n_needed, descending=True):
    """
    Given an array of 'ratings', select at least 'n_needed' items
    from the highest (or lowest) end. If a tie occurs at the boundary
    rating, include all sketches that share that rating.

    Parameters:
    -----------
    ratings : array-like
        The rater's scores for each sketch.
    n_needed : int
        Minimum number of sketches to include in the top set.
    descending : bool
        If True, take from the highest scores (i.e., top N%).
        If False, take from the lowest scores (i.e., bottom N%), etc.

    Returns:
    --------
    top_indices : set of int
        Indices of all sketches included in the top set (>= boundary rating).
    """

    # Sort sketches by rating (descending by default).
    # 'idx' is the original index, 'score' is the rating.
    sorted_pairs = sorted(enumerate(ratings), key=lambda x: x[1], reverse=descending)

    # If n_needed > total sketches, just return all.
    if n_needed >= len(ratings):
        return set(range(len(ratings)))

    # rating at the boundary index
    boundary_score = sorted_pairs[n_needed - 1][1]

    # Collect everything with rating >= boundary_score (if descending),
    # or <= boundary_score (if ascending).
    top_indices = set()
    if descending:
        for (idx, score) in sorted_pairs:
            if score >= boundary_score:
                top_indices.add(idx)
            else:
                break
    else:
        # if you ever need a bottom-X% approach
        for (idx, score) in reversed(sorted_pairs):  # ascending logic
            if score <= boundary_score:
                top_indices.add(idx)
            else:
                break
    return top_indices


def jaccard_similarity(setA, setB):
    """
    Compute Jaccard similarity between two sets:
    J(A,B) = |A intersect B| / |A union B|.
    """
    if not setA and not setB:
        return 1.0  # or define 0.0 in case of empty sets
    return len(setA.intersection(setB)) / len(setA.union(setB))


def plot_jaccard_vs_cutoff(e1, e2, mA, mB, cutoffs=None):
    """
    Plots the Jaccard similarity between Expert1 top sets and
    {Expert2, ModelA, ModelB} top sets, across multiple cutoffs.

    e1, e2, mA, mB : array-like
        Ratings for each of the four raters, same length.
    cutoffs : list of floats
        Each float is e.g. 0.05 = 5%, 0.10 = 10%, etc.
    """
    if cutoffs is None:
        cutoffs = [0.05, 0.1, 0.15, 0.2, 0.25]

    n_total = len(e1)

    # Arrays to store Jaccard at each cutoff
    j_e1_e2 = []
    j_e1_mA = []
    j_e1_mB = []

    for fraction in cutoffs:
        # 1) Find Expert1's top set (descending)
        n_needed_e1 = int(np.ceil(n_total * fraction))
        topE1 = get_top_set_with_ties(e1, n_needed_e1, descending=True)

        # Size of Expert1's top set:
        actual_top_size_e1 = len(topE1)

        # 2) Build Expert2's top set with at least actual_top_size_e1 items
        topE2 = get_top_set_with_ties(e2, actual_top_size_e1, descending=True)
        # 3) Similarly for ModelA, ModelB
        topMA = get_top_set_with_ties(mA, actual_top_size_e1, descending=True)
        topMB = get_top_set_with_ties(mB, actual_top_size_e1, descending=True)

        # 4) Compute Jaccard similarity
        j_e1_e2.append(jaccard_similarity(topE1, topE2))
        j_e1_mA.append(jaccard_similarity(topE1, topMA))
        j_e1_mB.append(jaccard_similarity(topE1, topMB))

    # Plot
    plt.figure(figsize=(7,5))
    plt.plot(cutoffs, j_e1_e2, marker='o', label='Expert1 vs Expert2')
    plt.plot(cutoffs, j_e1_mA, marker='o', label='Expert1 vs ModelA')
    plt.plot(cutoffs, j_e1_mB, marker='o', label='Expert1 vs ModelB')
    plt.xlabel('Fraction Cutoff (Top X% of Expert1 Ratings)')
    plt.ylabel('Jaccard Similarity')
    plt.title('Jaccard Similarity vs. Cutoff (Reference: Expert1)')
    plt.legend()
    plt.grid(True)
    plt.show()

    plt.savefig("jaccard_comparison.png", dpi=600)


def get_top_set_with_ties(ratings, n_needed, descending=True):
    """
    Given an array of 'ratings', select at least 'n_needed' items
    from the highest (or lowest) end. If a tie occurs at the boundary
    rating, include all sketches that share that rating.

    Parameters:
    -----------
    ratings : array-like
        The rater's scores for each sketch.
    n_needed : int
        Minimum number of sketches to include in the top set.
    descending : bool
        If True, take from the highest scores (i.e., top N%).
        If False, take from the lowest scores (i.e., bottom N%), etc.

    Returns:
    --------
    top_indices : set of int
        Indices of all sketches included in the top set (>= boundary rating).
    """

    # Sort sketches by rating (descending by default).
    # 'idx' is the original index, 'score' is the rating.
    sorted_pairs = sorted(enumerate(ratings), key=lambda x: x[1], reverse=descending)

    # If n_needed > total sketches, just return all.
    if n_needed >= len(ratings):
        return set(range(len(ratings)))

    # rating at the boundary index
    boundary_score = sorted_pairs[n_needed - 1][1]

    # Collect everything with rating >= boundary_score (if descending),
    # or <= boundary_score (if ascending).
    top_indices = set()
    if descending:
        for (idx, score) in sorted_pairs:
            if score >= boundary_score:
                top_indices.add(idx)
            else:
                break
    else:
        # if you ever need a bottom-X% approach
        for (idx, score) in reversed(sorted_pairs):  # ascending logic
            if score <= boundary_score:
                top_indices.add(idx)
            else:
                break
    return top_indices


def jaccard_similarity(setA, setB):
    """
    Compute Jaccard similarity between two sets:
    J(A,B) = |A intersect B| / |A union B|.
    """
    if not setA and not setB:
        return 1.0  # or define 0.0 in case of empty sets
    return len(setA.intersection(setB)) / len(setA.union(setB))


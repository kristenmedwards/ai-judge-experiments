#############################################
# Custom TOST function for paired samples
#############################################
def ttost_paired(x, y, low, high, alpha=0.05):
    """
    Perform a paired Two One-Sided Tests (TOST) equivalence test.

    Parameters:
    -----------
    x, y : array-like
        Paired samples.
    low : float
        Lower equivalence bound.
    high : float
        Upper equivalence bound.
    alpha : float
        Significance level.

    Returns:
    --------
    result : pandas.DataFrame
        A one-row DataFrame containing:
          - T1: t-statistic for test that mean(x-y) > low
          - p1: one-sided p-value for T1
          - T2: t-statistic for test that mean(x-y) < high
          - p2: one-sided p-value for T2
          - mean_diff: mean of differences (x-y)
          - sd_diff: standard deviation of differences
          - n: sample size
    """

    d = np.array(x) - np.array(y)
    n = len(d)
    mean_d = np.mean(d)
    sd_d = np.std(d, ddof=1)
    se_d = sd_d / np.sqrt(n)

    # Test that mean difference is greater than low bound:
    t1 = (mean_d - low) / se_d
    p1 = 1 - t.cdf(t1, df=n-1)

    # Test that mean difference is less than high bound:
    t2 = (mean_d - high) / se_d
    p2 = t.cdf(t2, df=n-1)

    result = pd.DataFrame({
        'T1': [t1],
        'p1': [p1],
        'T2': [t2],
        'p2': [p2],
        'mean_diff': [mean_d],
        'sd_diff': [sd_d],
        'n': [n]
    })
    return result


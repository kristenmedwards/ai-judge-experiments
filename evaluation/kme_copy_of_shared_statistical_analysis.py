def evaluate_metric_with_interpretation(
    expert1, expert2, modelA, modelB,
    equivalence_margin=1.14, # This assumes that on average, experts vary by 2.0 points. Lower this margin if we believe human equivalence should be more strict.
    min_kappa_expert=None,
    min_icc_expert=None,
    min_spearman_expert=None
):
    """
    Conducts a comprehensive evaluation of a single metric following the
    decision criteria:
      1) Agreement (Weighted Kappa, ICC).
      2) Error Metrics (MAE, RMSE), incl. Bland-Altman for one AI-expert pair.
      3) Distribution Differences (Friedman + post-hoc).
      4) Correlation Analysis (Spearman).
      5) Equivalence Testing (TOST).
      6) Automatic interpretation relative to the 6 "human-level" conditions.
      7) Model A vs Model B comparison.

    Parameters:
    -----------
    expert1, expert2, modelA, modelB : array-like of shape (984,)
    equivalence_margin : float
        Bounds for TOST equivalence testing (e.g., +/-1.0).
    min_kappa_expert : float or None
        A reference Weighted Kappa for Expert-Expert. If None, will be computed from data.
    min_icc_expert   : float or None
        A reference ICC for Expert-Expert. If None, will be derived or set.
    min_spearman_expert : float or None
        A reference Spearman correlation for Expert-Expert. If None, will be computed.

    Returns:
    --------
    results : dict
        All computed statistics, plus a textual interpretation.
    """

    # Convert inputs to numpy arrays
    e1 = np.array(expert1)
    e2 = np.array(expert2)
    mA = np.array(modelA)
    mB = np.array(modelB)


    # Prepare results storage
    results = {
        'agreement': {},
        'error': {},
        'distribution': {},
        'correlation': {},
        'equivalence': {},
        'model_comparison': {},
        'interpretation': {},
    }

    ##############################################################################
    # 1) Inter-Rater Agreement (Weighted Kappa & ICC)
    ##############################################################################
    # Expert-Expert Weighted Kappa using scikit-learn's cohen_kappa_score
    # Note that the ratings are rounded here, as it expects integers. This is an assumption with some consequences.

    rounded_e1 = np.round(e1)
    rounded_e2 = np.round(e2)
    rounded_mA = np.round(mA)
    rounded_mB = np.round(mB)


    kappa_e1_e2 = cohen_kappa_score(rounded_e1, rounded_e2, weights='quadratic')



    # Compute Weighted Kappa for AI-Expert pairs as well
    kappa_e1_mA = cohen_kappa_score(rounded_e1, rounded_mA, weights='quadratic')
    kappa_e1_mB = cohen_kappa_score(rounded_e1, rounded_mB, weights='quadratic')
    kappa_e2_mA = cohen_kappa_score(rounded_e2, rounded_mA, weights='quadratic')
    kappa_e2_mB = cohen_kappa_score(rounded_e2, rounded_mB, weights='quadratic')







    # Intraclass Correlation
    df_icc = pd.DataFrame({
        'SketchID': np.tile(np.arange(len(e1)), 4),
        'Rater': np.repeat(['E1','E2','MA','MB'], len(e1)),
        'Rating': np.concatenate([e1, e2, mA, mB])
    })
    # ICC across all 4 raters
    icc_all = pg.intraclass_corr(data=df_icc, targets='SketchID', raters='Rater', ratings='Rating')
    # Extract ICC(2,1) - "random raters, absolute agreement"
    icc2_row = icc_all.loc[icc_all['Type']=='ICC2']
    icc2_all = icc2_row['ICC'].values[0] if len(icc2_row)>0 else np.nan

    # Compute only E1-E2 as the human-human baseline:
    df_icc_e1_e2 = df_icc[df_icc['Rater'].isin(['E1','E2'])]
    icc_e1_e2 = pg.intraclass_corr(
        data=df_icc_e1_e2, targets='SketchID', raters='Rater', ratings='Rating'
    )
    icc2_e1_e2 = icc_e1_e2.loc[icc_e1_e2['Type']=='ICC2','ICC'].values[0]

    # Similarly, compute E1-MA
    df_icc_e1_mA = df_icc[df_icc['Rater'].isin(['E1','MA'])]
    icc_e1_mA = pg.intraclass_corr(
        data=df_icc_e1_mA, targets='SketchID', raters='Rater', ratings='Rating'
    )
    icc2_e1_mA = icc_e1_mA.loc[icc_e1_mA['Type']=='ICC2','ICC'].values[0]

    # Similarly, E1-MB
    df_icc_e1_mB = df_icc[df_icc['Rater'].isin(['E1','MB'])]
    icc_e1_mB = pg.intraclass_corr(
        data=df_icc_e1_mB, targets='SketchID', raters='Rater', ratings='Rating'
    )
    icc2_e1_mB = icc_e1_mB.loc[icc_e1_mB['Type']=='ICC2','ICC'].values[0]

    # And for E2-MA and E2-MB:
    df_icc_e2_mA = df_icc[df_icc['Rater'].isin(['E2','MA'])]
    icc_e2_mA = pg.intraclass_corr(
        data=df_icc_e2_mA, targets='SketchID', raters='Rater', ratings='Rating'
    )
    icc2_e2_mA = icc_e2_mA.loc[icc_e2_mA['Type']=='ICC2','ICC'].values[0]

    df_icc_e2_mB = df_icc[df_icc['Rater'].isin(['E2','MB'])]
    icc_e2_mB = pg.intraclass_corr(
        data=df_icc_e2_mB, targets='SketchID', raters='Rater', ratings='Rating'
    )
    icc2_e2_mB = icc_e2_mB.loc[icc_e2_mB['Type']=='ICC2','ICC'].values[0]

    results['agreement']['weighted_kappa'] = {
        'E1_E2': kappa_e1_e2,
        'E1_MA': kappa_e1_mA,
        'E1_MB': kappa_e1_mB,
        'E2_MA': kappa_e2_mA,
        'E2_MB': kappa_e2_mB
    }
    results['agreement']['ICC2'] = {
        'All4': icc2_all,    # overall among E1, E2, MA, MB
        'E1_E2': icc2_e1_e2,
        'E1_MA': icc2_e1_mA,
        'E1_MB': icc2_e1_mB,
        'E2_MA': icc2_e2_mA,
        'E2_MB': icc2_e2_mB
    }

    # Set baseline references if not provided
    if min_kappa_expert is None:
        min_kappa_expert = kappa_e1_e2
    if min_icc_expert is None:
        min_icc_expert = icc2_e1_e2

    ##############################################################################
    # 2) Error Metrics (MAE, RMSE) + Bland-Altman
    ##############################################################################
    diff_e1_e2 = e1 - e2
    mae_e1_e2 = np.mean(np.abs(diff_e1_e2))
    rmse_e1_e2 = np.sqrt(np.mean(diff_e1_e2**2))

    mae_mA_e1 = np.mean(np.abs(mA - e1))
    mae_mA_e2 = np.mean(np.abs(mA - e2))
    mae_mB_e1 = np.mean(np.abs(mB - e1))
    mae_mB_e2 = np.mean(np.abs(mB - e2))

    rmse_mA_e1 = np.sqrt(np.mean((mA - e1)**2))
    rmse_mA_e2 = np.sqrt(np.mean((mA - e2)**2))
    rmse_mB_e1 = np.sqrt(np.mean((mB - e1)**2))
    rmse_mB_e2 = np.sqrt(np.mean((mB - e2)**2))

    results['error']['mae'] = {
        'E1_E2': mae_e1_e2,
        'MA_E1': mae_mA_e1,
        'MA_E2': mae_mA_e2,
        'MB_E1': mae_mB_e1,
        'MB_E2': mae_mB_e2
    }
    results['error']['rmse'] = {
        'E1_E2': rmse_e1_e2,
        'MA_E1': rmse_mA_e1,
        'MA_E2': rmse_mA_e2,
        'MB_E1': rmse_mB_e1,
        'MB_E2': rmse_mB_e2
    }

    # Bland-Altman for E1 vs ModelA (repeat this for E1 vs ModelB and so on)
    mean_ratings = 0.5*(e1 + mA)
    diff_ratings = e1 - mA
    mean_diff = np.mean(diff_ratings)
    sd_diff = np.std(diff_ratings, ddof=1)
    results['error']['bland_altman_example'] = {
        'mean_diff': mean_diff,
        'sd_diff': sd_diff,
        'upper_loa': mean_diff + 1.96*sd_diff,
        'lower_loa': mean_diff - 1.96*sd_diff
    }

    # Plot Bland-Altman inline:
    fig, ax = plt.subplots()
    ax.scatter(mean_ratings, diff_ratings, alpha=0.4)
    ax.axhline(mean_diff, color='red', linestyle='--', label=f'Mean diff={mean_diff:.2f}')
    ax.axhline(mean_diff+1.96*sd_diff, color='gray', linestyle=':')
    ax.axhline(mean_diff-1.96*sd_diff, color='gray', linestyle=':')
    ax.set_title('Bland–Altman: Expert1 vs. ModelA')
    ax.set_xlabel('(E1 + MA)/2')
    ax.set_ylabel('E1 - MA')
    ax.legend()
    plt.show()


    ############## Bland Altman E2 vs Model A ######################
        # Bland-Altman for E1 vs ModelA (repeat this for E1 vs ModelB and so on)
    mean_ratings = 0.5*(e2 + mA)
    diff_ratings = e2 - mA
    mean_diff = np.mean(diff_ratings)
    sd_diff = np.std(diff_ratings, ddof=1)
    results['error']['bland_altman_example'] = {
        'mean_diff': mean_diff,
        'sd_diff': sd_diff,
        'upper_loa': mean_diff + 1.96*sd_diff,
        'lower_loa': mean_diff - 1.96*sd_diff
    }

    # Plot Bland-Altman inline:
    fig, ax = plt.subplots()
    ax.scatter(mean_ratings, diff_ratings, alpha=0.4)
    ax.axhline(mean_diff, color='red', linestyle='--', label=f'Mean diff={mean_diff:.2f}')
    ax.axhline(mean_diff+1.96*sd_diff, color='gray', linestyle=':')
    ax.axhline(mean_diff-1.96*sd_diff, color='gray', linestyle=':')
    ax.set_title('Bland–Altman: Expert1 vs. ModelA')
    ax.set_xlabel('(E1 + MA)/2')
    ax.set_ylabel('E1 - MA')
    ax.legend()
    plt.show()

    ##############################################################################
    # 3) Distribution Differences: Friedman Test + Post-hoc
    ##############################################################################
    df_friedman = pd.DataFrame({
        'E1': e1,
        'E2': e2,
        'MA': mA,
        'MB': mB
    })
    friedman_res = pg.friedman(df_friedman)
    friedman_p = friedman_res['p-unc'].iloc[0]
    results['distribution']['friedman'] = {
        'Q': friedman_res['Q'].iloc[0],
        'ddof': friedman_res['ddof1'].iloc[0],
        'pval': friedman_p
    }

    if friedman_p < 0.05:
        df_melt = df_friedman.melt(var_name='Rater', value_name='Score', ignore_index=False)
        df_melt['Subject'] = df_melt.index
        posthoc = pg.pairwise_tests(
            data=df_melt,
            dv='Score', within='Rater', subject='Subject',
            parametric=False, padjust='bonf'
        )
        results['distribution']['posthoc'] = posthoc
    else:
        results['distribution']['posthoc'] = "No significant difference overall; skipping post-hoc."

    ##############################################################################
    # 4) Correlation Analysis (Spearman)
    ##############################################################################
    spear_e1_e2 = st.spearmanr(e1, e2)
    spear_e1_mA = st.spearmanr(e1, mA)
    spear_e1_mB = st.spearmanr(e1, mB)
    spear_e2_mA = st.spearmanr(e2, mA)
    spear_e2_mB = st.spearmanr(e2, mB)

    results['correlation']['spearman_corr'] = {
        'E1_E2': spear_e1_e2.correlation,
        'E1_MA': spear_e1_mA.correlation,
        'E1_MB': spear_e1_mB.correlation,
        'E2_MA': spear_e2_mA.correlation,
        'E2_MB': spear_e2_mB.correlation
    }
    results['correlation']['spearman_pval'] = {
        'E1_E2': spear_e1_e2.pvalue,
        'E1_MA': spear_e1_mA.pvalue,
        'E1_MB': spear_e1_mB.pvalue,
        'E2_MA': spear_e2_mA.pvalue,
        'E2_MB': spear_e2_mB.pvalue
    }

    if min_spearman_expert is None:
        min_spearman_expert = spear_e1_e2.correlation

    ##############################################################################
    # 5) Equivalence Testing (TOST)
    ##############################################################################
    # We use our custom function.
    def tost_equivalence(a, b, bound=equivalence_margin, alpha=0.05):
        return ttost_paired(a, b, low=-bound, high=bound, alpha=alpha)

    eq_mA_e1 = tost_equivalence(mA, e1)
    eq_mA_e2 = tost_equivalence(mA, e2)
    eq_mB_e1 = tost_equivalence(mB, e1)
    eq_mB_e2 = tost_equivalence(mB, e2)

    results['equivalence']['MA_E1'] = eq_mA_e1
    results['equivalence']['MA_E2'] = eq_mA_e2
    results['equivalence']['MB_E1'] = eq_mB_e1
    results['equivalence']['MB_E2'] = eq_mB_e2

    ##############################################################################
    # 6) Model A vs. Model B Comparison
    ##############################################################################
    errA_e1 = np.abs(mA - e1)
    errB_e1 = np.abs(mB - e1)
    wb_res_e1 = pg.wilcoxon(errA_e1, errB_e1, alternative='two-sided')

    errA_e2 = np.abs(mA - e2)
    errB_e2 = np.abs(mB - e2)
    wb_res_e2 = pg.wilcoxon(errA_e2, errB_e2, alternative='two-sided')

    results['model_comparison']['abs_error_test'] = {
        'E1': wb_res_e1,
        'E2': wb_res_e2
    }

    ##############################################################################
    # 7) Automatic Interpretation (Decision Criteria)
    ##############################################################################
    interpretation_text = []

    #Note to self: May need to revisit 0.8 cut-off for this application
    def check_ballpark_kappa(kappa_ai, kappa_expert, fraction=0.8):
        return kappa_ai >= (kappa_expert * fraction)

    def check_ballpark_icc(icc_ai, icc_expert, fraction=0.8):
        return icc_ai >= (icc_expert * fraction)

    def interpret_model_vs_expert(e_mae, baseline_mae, e_kappa, baseline_kappa, e_icc, baseline_icc,
                                  e_spear, baseline_spear, eq_res,
                                  friedman_p, posthoc, alpha=0.05):
        """
        Return a dictionary with boolean flags for each decision criterion.
        """
        cr = {}
        crit1_kappa = check_ballpark_kappa(e_kappa, baseline_kappa)
        crit1_icc   = check_ballpark_icc(e_icc, baseline_icc)
        cr['agreement_ok'] = (crit1_kappa and crit1_icc)
        cr['error_within_expert'] = (e_mae <= baseline_mae)
        if friedman_p < alpha and isinstance(posthoc, pd.DataFrame):
            cr['no_significant_difference'] = True
        else:
            cr['no_significant_difference'] = True
        p1, p2 = eq_res['p1'].values[0], eq_res['p2'].values[0]
        cr['equivalence'] = (p1 < alpha and p2 < alpha)
        cr['corr_ok'] = (e_spear >= 0.8 * baseline_spear) if baseline_spear > 0 else (e_spear > 0.5)
        return cr

    baseline_kappa = kappa_e1_e2
    baseline_icc   = icc2_e1_e2
    baseline_spear = spear_e1_e2.correlation

    posthoc_df = None
    if friedman_p < 0.05 and isinstance(results['distribution']['posthoc'], pd.DataFrame):
        posthoc_df = results['distribution']['posthoc']

    cA_E1 = interpret_model_vs_expert(
        e_mae=mae_mA_e1,
        baseline_mae=mae_e1_e2,
        e_kappa=kappa_e1_mA,
        baseline_kappa=baseline_kappa,
        e_icc=icc2_e1_mA,
        baseline_icc=baseline_icc,
        e_spear=spear_e1_mA.correlation,
        baseline_spear=baseline_spear,
        eq_res=eq_mA_e1,
        friedman_p=friedman_p,
        posthoc=posthoc_df
    )

    cA_E2 = interpret_model_vs_expert(
        e_mae=mae_mA_e2,
        baseline_mae=mae_e1_e2,
        e_kappa=kappa_e2_mA,
        baseline_kappa=baseline_kappa,
        e_icc=icc2_e2_mA,
        baseline_icc=baseline_icc,
        e_spear=spear_e2_mA.correlation,
        baseline_spear=baseline_spear,
        eq_res=eq_mA_e2,
        friedman_p=friedman_p,
        posthoc=posthoc_df
    )

    cB_E1 = interpret_model_vs_expert(
        e_mae=mae_mB_e1,
        baseline_mae=mae_e1_e2,
        e_kappa=kappa_e1_mB,
        baseline_kappa=baseline_kappa,
        e_icc=icc2_e1_mB,
        baseline_icc=baseline_icc,
        e_spear=spear_e1_mB.correlation,
        baseline_spear=baseline_spear,
        eq_res=eq_mB_e1,
        friedman_p=friedman_p,
        posthoc=posthoc_df
    )

    cB_E2 = interpret_model_vs_expert(
        e_mae=mae_mB_e2,
        baseline_mae=mae_e1_e2,
        e_kappa=kappa_e2_mB,
        baseline_kappa=baseline_kappa,
        e_icc=icc2_e2_mB,
        baseline_icc=baseline_icc,
        e_spear=spear_e2_mB.correlation,
        baseline_spear=baseline_spear,
        eq_res=eq_mB_e2,
        friedman_p=friedman_p,
        posthoc=posthoc_df
    )

    results['interpretation']['ModelA_vs_Expert1'] = cA_E1
    results['interpretation']['ModelA_vs_Expert2'] = cA_E2
    results['interpretation']['ModelB_vs_Expert1'] = cB_E1
    results['interpretation']['ModelB_vs_Expert2'] = cB_E2

    final_message = []
    def criteria_summary_str(crit_dict):
        met = [k for k, v in crit_dict.items() if v]
        not_met = [k for k, v in crit_dict.items() if not v]
        return f"Criteria met: {met}, Criteria NOT met: {not_met}"

    final_message.append("=== ModelA vs Expert1 ===")
    final_message.append(criteria_summary_str(cA_E1))
    final_message.append("=== ModelA vs Expert2 ===")
    final_message.append(criteria_summary_str(cA_E2))
    final_message.append("=== ModelB vs Expert1 ===")
    final_message.append(criteria_summary_str(cB_E1))
    final_message.append("=== ModelB vs Expert2 ===")
    final_message.append(criteria_summary_str(cB_E2))

    # Evaluate model comparison via absolute error using Wilcoxon test results
    p_e1 = results['model_comparison']['abs_error_test']['E1']['p-val'].values[0]
    mean_errA_e1 = np.mean(np.abs(mA - e1))
    mean_errB_e1 = np.mean(np.abs(mB - e1))
    if p_e1 < 0.05:
        model_comp_e1_msg = ("ModelA significantly outperforms ModelB (Expert1 reference)."
                             if mean_errA_e1 < mean_errB_e1 else
                             "ModelB significantly outperforms ModelA (Expert1 reference).")
    else:
        model_comp_e1_msg = "No significant difference between ModelA and ModelB (Expert1 reference)."

    p_e2 = results['model_comparison']['abs_error_test']['E2']['p-val'].values[0]
    mean_errA_e2 = np.mean(np.abs(mA - e2))
    mean_errB_e2 = np.mean(np.abs(mB - e2))
    if p_e2 < 0.05:
        model_comp_e2_msg = ("ModelA significantly outperforms ModelB (Expert2 reference)."
                             if mean_errA_e2 < mean_errB_e2 else
                             "ModelB significantly outperforms ModelA (Expert2 reference).")
    else:
        model_comp_e2_msg = "No significant difference between ModelA and ModelB (Expert2 reference)."

    final_message.append("=== ModelA vs ModelB Comparison ===")
    final_message.append(f"Expert1 reference: {model_comp_e1_msg}")
    final_message.append(f"Expert2 reference: {model_comp_e2_msg}")

    results['interpretation']['text_summary'] = "\n".join(final_message)

    return results

